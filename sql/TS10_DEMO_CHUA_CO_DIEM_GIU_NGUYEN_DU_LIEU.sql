-- View phục vụ tra cứu kết quả khi đã phê duyệt (không tạo trước kết quả).
CREATE OR REPLACE VIEW vw_danh_sach_trung_tuyen AS
SELECT k.ma_ky_thi,p.so_bao_danh,t.ma_thi_sinh,t.ho_ten,k.tong_diem,
 k.nguyen_vong_trung_tuyen,k.ma_truong,s.ten_truong,k.trang_thai
FROM ket_qua_xet_tuyen k
JOIN thi_sinh t ON t.ma_thi_sinh=k.ma_thi_sinh
LEFT JOIN phan_bo_thi_sinh p ON p.ma_thi_sinh=t.ma_thi_sinh AND p.ma_ky_thi=k.ma_ky_thi
JOIN truong_thpt s ON s.ma_truong=k.ma_truong
WHERE k.ket_qua='TRUNG_TUYEN' AND k.trang_thai='DA_DUYET';

CREATE OR REPLACE VIEW vw_thong_ke_tuyen_sinh AS
SELECT k.ma_ky_thi, COUNT(*) AS tong_thi_sinh,
 SUM(k.ket_qua='TRUNG_TUYEN') AS so_trung_tuyen,
 SUM(k.ket_qua='KHONG_TRUNG_TUYEN') AS so_khong_trung_tuyen,
 SUM(k.trang_thai='DA_DUYET') AS so_da_duyet
FROM ket_qua_xet_tuyen k GROUP BY k.ma_ky_thi;
