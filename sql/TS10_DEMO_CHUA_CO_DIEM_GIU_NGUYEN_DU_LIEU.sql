DROP DATABASE IF EXISTS tuyensinh10;
CREATE DATABASE IF NOT EXISTS tuyensinh10 CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE tuyensinh10;
CREATE TABLE IF NOT EXISTS nguoi_dung(id INT AUTO_INCREMENT PRIMARY KEY, ten_dang_nhap VARCHAR(80) NOT NULL UNIQUE, mat_khau_hash VARCHAR(255) NOT NULL, ho_ten VARCHAR(120) NOT NULL, vai_tro ENUM('SO','THU_KY','HOI_DONG','THPT','THCS') NOT NULL, trang_thai TINYINT NOT NULL DEFAULT 1);
CREATE TABLE IF NOT EXISTS truong_thpt(ma_truong VARCHAR(10) PRIMARY KEY,ten_truong VARCHAR(150) NOT NULL,kha_nang_tiep_nhan INT NOT NULL,CHECK(kha_nang_tiep_nhan>=0));
CREATE TABLE IF NOT EXISTS ky_thi(ma_ky_thi VARCHAR(10) PRIMARY KEY,ten_ky_thi VARCHAR(150) NOT NULL,nam_tuyen_sinh INT NOT NULL);
CREATE TABLE IF NOT EXISTS he_xet_tuyen(ma_he VARCHAR(10) PRIMARY KEY,ten_he VARCHAR(100) NOT NULL);
CREATE TABLE IF NOT EXISTS chi_tieu(ma_chi_tieu INT AUTO_INCREMENT PRIMARY KEY,ma_ky_thi VARCHAR(10) NOT NULL,ma_truong VARCHAR(10) NOT NULL,ma_he VARCHAR(10) NOT NULL,so_luong INT NOT NULL,trang_thai ENUM('DU_KIEN','DA_DUYET') NOT NULL DEFAULT 'DU_KIEN',nguoi_duyet INT NULL,ngay_duyet DATETIME NULL,UNIQUE(ma_ky_thi,ma_truong,ma_he),FOREIGN KEY(ma_ky_thi) REFERENCES ky_thi(ma_ky_thi),FOREIGN KEY(ma_truong) REFERENCES truong_thpt(ma_truong),FOREIGN KEY(ma_he) REFERENCES he_xet_tuyen(ma_he),FOREIGN KEY(nguoi_duyet) REFERENCES nguoi_dung(id),CHECK(so_luong>=0));
CREATE TABLE IF NOT EXISTS thi_sinh(ma_thi_sinh VARCHAR(10) PRIMARY KEY,ho_ten VARCHAR(100) NOT NULL,ngay_sinh DATE NULL,ma_ky_thi VARCHAR(10) NOT NULL,ho_so_hop_le TINYINT NOT NULL DEFAULT 0,FOREIGN KEY(ma_ky_thi) REFERENCES ky_thi(ma_ky_thi));
CREATE TABLE IF NOT EXISTS dia_diem_thi(ma_dia_diem VARCHAR(10) PRIMARY KEY,ten_dia_diem VARCHAR(150) NOT NULL,dia_chi VARCHAR(255) NOT NULL);
CREATE TABLE IF NOT EXISTS phong_thi(ma_phong VARCHAR(10) PRIMARY KEY,ma_ky_thi VARCHAR(10) NOT NULL,ma_dia_diem VARCHAR(10) NOT NULL,ten_phong VARCHAR(50) NOT NULL,suc_chua INT NOT NULL,FOREIGN KEY(ma_ky_thi) REFERENCES ky_thi(ma_ky_thi),FOREIGN KEY(ma_dia_diem) REFERENCES dia_diem_thi(ma_dia_diem),CHECK(suc_chua>0));
CREATE TABLE IF NOT EXISTS phan_bo_thi_sinh(id INT AUTO_INCREMENT PRIMARY KEY,ma_ky_thi VARCHAR(10) NOT NULL,ma_thi_sinh VARCHAR(10) NOT NULL,ma_phong VARCHAR(10) NOT NULL,so_bao_danh VARCHAR(20) NOT NULL,trang_thai ENUM('DU_KIEN','DA_XAC_NHAN') NOT NULL DEFAULT 'DU_KIEN',UNIQUE(ma_ky_thi,ma_thi_sinh),UNIQUE(ma_ky_thi,so_bao_danh),FOREIGN KEY(ma_ky_thi) REFERENCES ky_thi(ma_ky_thi),FOREIGN KEY(ma_thi_sinh) REFERENCES thi_sinh(ma_thi_sinh),FOREIGN KEY(ma_phong) REFERENCES phong_thi(ma_phong));
CREATE TABLE IF NOT EXISTS mon_thi(ma_mon VARCHAR(10) PRIMARY KEY,ten_mon VARCHAR(100) NOT NULL);
CREATE TABLE IF NOT EXISTS nhan_su(ma_ns VARCHAR(10) PRIMARY KEY,ho_ten VARCHAR(100) NOT NULL,loai_nhan_su VARCHAR(60) NOT NULL);
CREATE TABLE IF NOT EXISTS tui_bai_thi(ma_tui VARCHAR(10) PRIMARY KEY,ma_ky_thi VARCHAR(10) NOT NULL,ma_mon VARCHAR(10) NOT NULL,ma_phong VARCHAR(10) NOT NULL,ma_bi VARCHAR(30) NOT NULL UNIQUE,FOREIGN KEY(ma_ky_thi) REFERENCES ky_thi(ma_ky_thi),FOREIGN KEY(ma_mon) REFERENCES mon_thi(ma_mon),FOREIGN KEY(ma_phong) REFERENCES phong_thi(ma_phong));
CREATE TABLE IF NOT EXISTS phan_cong_cham_thi(id INT AUTO_INCREMENT PRIMARY KEY,ma_tui VARCHAR(10) NOT NULL UNIQUE,ma_cbct1 VARCHAR(10) NOT NULL,ma_cbct2 VARCHAR(10) NOT NULL,trang_thai ENUM('DA_PHAN_CONG','HOAN_TAT') NOT NULL DEFAULT 'DA_PHAN_CONG',FOREIGN KEY(ma_tui) REFERENCES tui_bai_thi(ma_tui),FOREIGN KEY(ma_cbct1) REFERENCES nhan_su(ma_ns),FOREIGN KEY(ma_cbct2) REFERENCES nhan_su(ma_ns),CHECK(ma_cbct1<>ma_cbct2));
-- ma_thi_sinh chỉ có ở bảng ánh xạ cách ly, không hiển thị ở màn hình chấm thi.
CREATE TABLE IF NOT EXISTS bai_thi(ma_bai VARCHAR(10) PRIMARY KEY,ma_tui VARCHAR(10) NOT NULL,ma_phach VARCHAR(30) NOT NULL UNIQUE,ma_thi_sinh VARCHAR(10) NOT NULL,da_thong_nhat_diem TINYINT NOT NULL DEFAULT 0,FOREIGN KEY(ma_tui) REFERENCES tui_bai_thi(ma_tui),FOREIGN KEY(ma_thi_sinh) REFERENCES thi_sinh(ma_thi_sinh));
CREATE TABLE IF NOT EXISTS diem_thi(id INT AUTO_INCREMENT PRIMARY KEY,ma_bai VARCHAR(10) NOT NULL UNIQUE,diem DECIMAL(4,2) NOT NULL,trang_thai ENUM('DA_NHAP','DA_CHOT') NOT NULL DEFAULT 'DA_NHAP',nguoi_nhap INT NOT NULL,ngay_nhap DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,nguoi_chot INT NULL,ngay_chot DATETIME NULL,FOREIGN KEY(ma_bai) REFERENCES bai_thi(ma_bai),FOREIGN KEY(nguoi_nhap) REFERENCES nguoi_dung(id),FOREIGN KEY(nguoi_chot) REFERENCES nguoi_dung(id),CHECK(diem BETWEEN 0 AND 10));
CREATE TABLE IF NOT EXISTS nguyen_vong(id INT AUTO_INCREMENT PRIMARY KEY,ma_thi_sinh VARCHAR(10) NOT NULL,ma_truong VARCHAR(10) NOT NULL,ma_he VARCHAR(10) NOT NULL,thu_tu INT NOT NULL,da_xac_nhan TINYINT NOT NULL DEFAULT 0,UNIQUE(ma_thi_sinh,thu_tu),UNIQUE(ma_thi_sinh,ma_truong,ma_he),FOREIGN KEY(ma_thi_sinh) REFERENCES thi_sinh(ma_thi_sinh),FOREIGN KEY(ma_truong) REFERENCES truong_thpt(ma_truong),FOREIGN KEY(ma_he) REFERENCES he_xet_tuyen(ma_he),CHECK(thu_tu BETWEEN 1 AND 3));
CREATE TABLE IF NOT EXISTS ket_qua_xet_tuyen(id INT AUTO_INCREMENT PRIMARY KEY,ma_thi_sinh VARCHAR(10) NOT NULL UNIQUE,ma_ky_thi VARCHAR(10) NOT NULL,ma_truong VARCHAR(10) NULL,nguyen_vong_trung_tuyen INT NULL,tong_diem DECIMAL(5,2) NOT NULL,ket_qua ENUM('TRUNG_TUYEN','KHONG_TRUNG_TUYEN') NOT NULL,trang_thai ENUM('DU_KIEN','DA_DUYET') NOT NULL DEFAULT 'DU_KIEN',nguoi_duyet INT NULL,ngay_duyet DATETIME NULL,FOREIGN KEY(ma_thi_sinh) REFERENCES thi_sinh(ma_thi_sinh),FOREIGN KEY(ma_ky_thi) REFERENCES ky_thi(ma_ky_thi),FOREIGN KEY(ma_truong) REFERENCES truong_thpt(ma_truong),FOREIGN KEY(nguoi_duyet) REFERENCES nguoi_dung(id),CHECK(nguyen_vong_trung_tuyen IS NULL OR nguyen_vong_trung_tuyen BETWEEN 1 AND 3));
CREATE TABLE IF NOT EXISTS nhat_ky_he_thong(id BIGINT AUTO_INCREMENT PRIMARY KEY,nguoi_dung INT NOT NULL,thao_tac VARCHAR(100) NOT NULL,noi_dung TEXT NOT NULL,thoi_gian DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,FOREIGN KEY(nguoi_dung) REFERENCES nguoi_dung(id));

